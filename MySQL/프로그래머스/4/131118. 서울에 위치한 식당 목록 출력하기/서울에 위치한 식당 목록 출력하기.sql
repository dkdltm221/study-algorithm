SELECT R.REST_ID,
    R.REST_NAME,
    R.FOOD_TYPE,
    R.FAVORITES,
    R.ADDRESS,
    ROUND(AVG(T.REVIEW_SCORE),2) AS SCORE
FROM REST_INFO R JOIN REST_REVIEW T ON R.REST_ID = T.REST_ID
WHERE R.ADDRESS LIKE "서울%"
GROUP BY R.REST_ID,
    R.REST_NAME,
    R.FOOD_TYPE,
    R.FAVORITES,R.ADDRESS
ORDER BY AVG(T.REVIEW_SCORE) DESC, R.FAVORITES DESC