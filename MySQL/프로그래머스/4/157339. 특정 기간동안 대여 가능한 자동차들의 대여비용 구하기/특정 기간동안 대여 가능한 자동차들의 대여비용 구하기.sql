WITH CAR_T AS (
    SELECT CAR_ID, CAR_TYPE, DAILY_FEE
    FROM CAR_RENTAL_COMPANY_CAR
    WHERE CAR_TYPE IN ('세단', 'SUV')
),
CAR_R AS (
    SELECT T.CAR_ID, T.CAR_TYPE, T.DAILY_FEE
    FROM CAR_T T
    WHERE NOT EXISTS (
        SELECT 1
        FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY R
        WHERE R.CAR_ID = T.CAR_ID
          AND R.START_DATE <= '2022-11-30'
          AND R.END_DATE >= '2022-11-01'
    )
),
CAR_FEE AS (
    SELECT T.CAR_ID,
           T.CAR_TYPE,
           FLOOR(30 * T.DAILY_FEE *
                 (1 - P.DISCOUNT_RATE / 100)) AS FEE
    FROM CAR_R T
    JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN P
        ON T.CAR_TYPE = P.CAR_TYPE
    WHERE P.DURATION_TYPE = '30일 이상'
)
SELECT CAR_ID, CAR_TYPE, FEE
FROM CAR_FEE
WHERE FEE >= 500000
  AND FEE < 2000000
ORDER BY FEE DESC, CAR_TYPE ASC, CAR_ID DESC;