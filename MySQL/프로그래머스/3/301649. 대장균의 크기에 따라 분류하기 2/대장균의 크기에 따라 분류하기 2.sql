SELECT ID,
    CASE
        WHEN E.TILE =1  THEN "CRITICAL"
        WHEN E.TILE = 2 THEN "HIGH"
        WHEN E.TILE = 3 THEN "MEDIUM"
        WHEN E.TILE =4 THEN "LOW"
    END AS COLONY_NAME
FROM (SELECT ID,NTILE(4) OVER (ORDER BY SIZE_OF_COLONY DESC) AS TILE FROM ECOLI_DATA) AS E
ORDER BY ID ASC;