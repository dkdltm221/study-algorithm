WITH FOOD AS (
    SELECT PRODUCT_ID,AMOUNT,PRODUCE_DATE
    FROM FOOD_ORDER
    WHERE PRODUCE_DATE >='2022-05-01' AND PRODUCE_DATE <'2022-06-01'
)
SELECT P.PRODUCT_ID,PRODUCT_NAME,SUM(PRICE*AMOUNT) AS TOTAL_SALES
FROM FOOD F JOIN FOOD_PRODUCT P ON F.PRODUCT_ID = P.PRODUCT_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME
ORDER BY TOTAL_SALES DESC,PRODUCT_ID ASC;